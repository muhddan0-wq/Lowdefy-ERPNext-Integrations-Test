"""Regenerate the "Appendix: JavaScript used in Appsmith" section of mes/PHASE1-REPORT.md from the widget sources.

Run after changing anything in mes/appsmith/widgets/ or the bindings in build_app.py:
    python mes/appsmith/update_report_appendix.py
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import build_app as b  # noqa: E402

REPORT = HERE.parent / "PHASE1-REPORT.md"
W = HERE / "widgets"
MARKER = "\n## Appendix: JavaScript used in Appsmith\n"
FILES = [
    ("common.js", "Shared by every page: bridge to Appsmith/ERPNext, formatting helpers, dialogs, navigation bar, external links"),
    ("work_orders.js", "Page Work Orders (M1): KPI tiles and filterable table"),
    ("wo_detail.js", "Page Work Order Detail (M1 + M4): header, operations, materials, Stop/Resume/Issue/Finish/Close"),
    ("new_plan.js", "Page New Plan (M3): finished goods, preview, create plan"),
    ("schedule_board.js", "Page Schedule Board (M2 + M5): Gantt coloured by product line or status, hover card, drag-and-drop rescheduling"),
    ("capacity.js", "Page Capacity (M2): workstation x day heat-map"),
    ("queue.js", "Page Workstation Queue (M6): operator Start/Pause/Resume/Complete, waiting-for-previous-operation check"),
]


def build():
    erp = b.erp_action("Work Orders")["unpublishedAction"]["actionConfiguration"]
    on_call = b.ON_CALL.replace("; })(", ";\n})(").replace(".then(", "\n  .then(").replace(".catch(", "\n  .catch(")
    out = [
        MARKER,
        "All JavaScript below runs in Appsmith. None of it decides anything about stock, capacity or the schedule: "
        "it only displays data and sends requests to the ERPNext API server scripts in `mes/server_scripts/`, "
        "which validate everything.",
        "",
        "How a request flows:",
        "",
        "1. The page's Custom Widget (`Main`) calls `MES.get()` or `MES.post()` (in `common.js`), which raises the "
        "Appsmith event `onCall` with `{id, path, body}`.",
        "2. The `onCall` handler runs the page's REST query `Erp` on the Appsmith server. The ERPNext API key lives "
        "only in the **ERPNext** datasource header, never in the browser.",
        "3. The answer is saved with `storeValue('mesResp_<id>')`. It flows back into the widget through its Default "
        "Model (`appsmith.store`), and the waiting promise in `common.js` resolves.",
        "",
        "The source files are in `mes/appsmith/widgets/`, and `mes/appsmith/build_app.py` packs them into "
        "`MES-Phase1.json`. Each page widget is `common.css` + `<page>.css` for CSS and `common.js` + `<page>.js` "
        "for JS; the HTML is just `<div id=\"app\"></div>`. This appendix is generated by "
        "`mes/appsmith/update_report_appendix.py`.",
        "",
        "### A.1 Appsmith wiring (identical on every page)",
        "",
        f"REST query `Erp` (datasource **ERPNext**, `{b.DATASOURCE_URL}`, header "
        "`Authorization: token <key>:<secret>`):",
        "",
        "| Setting | Value |",
        "|---|---|",
        f"| Method | `{erp['httpMethod']}` |",
        f"| Path | `{erp['path']}` |",
        f"| Body (JSON) | `{erp['body']}` |",
        "| Headers | `Content-Type: application/json`, `Accept: application/json` |",
        "| Timeout | 120 s |",
        "",
        "Custom Widget `Main`, Default Model:",
        "", "```javascript", b.DEFAULT_MODEL, "```", "",
        "Event `onCall`. The event context (`id`, `path`, `body`) is only in scope while the handler starts, "
        "so it is captured in an IIFE before `.then()`:",
        "", "```javascript", on_call, "```", "",
        "Event `onNavigate`. Page names open in the same window; full URLs (ERPNext desk links) open in a new, "
        "unsandboxed tab:",
        "", "```javascript", b.ON_NAVIGATE, "```", "",
    ]
    for i, (name, desc) in enumerate(FILES, start=2):
        code = (W / name).read_text(encoding="utf-8").rstrip()
        out += [f"### A.{i} `{name}`", "", desc + ".", "", "```javascript", code, "```", ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = REPORT.read_text(encoding="utf-8")
    head = text.split(MARKER)[0].rstrip() + "\n"
    REPORT.write_text(head + build(), encoding="utf-8")
    print(f"updated appendix in {REPORT}")
