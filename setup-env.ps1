param(
  [string]$SourceEnv = "F:\ERPNEXT\erpnextcomp_demo\.env",
  [switch]$Force
)

$ErrorActionPreference = "Stop"
$AppRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$TargetEnv = Join-Path $AppRoot ".env"

Write-Host "ERPNext Copilot - environment setup"
Write-Host "Reading ERPNext connection details from: $SourceEnv"

if (-not (Test-Path $SourceEnv)) {
  throw "Source .env not found at $SourceEnv. Pass -SourceEnv <path> pointing at an ERPNext .env that holds ERPNEXT_API_TOKEN."
}

if ((Test-Path $TargetEnv) -and -not $Force) {
  Write-Host ".env already exists. Use -Force to regenerate it." -ForegroundColor Yellow
  exit 0
}

$values = @{}
foreach ($line in Get-Content $SourceEnv) {
  $trimmed = $line.Trim()
  if ($trimmed -eq "" -or $trimmed.StartsWith("#")) { continue }
  $idx = $trimmed.IndexOf("=")
  if ($idx -lt 1) { continue }
  $values[$trimmed.Substring(0, $idx)] = $trimmed.Substring($idx + 1)
}

$token = $values["ERPNEXT_API_TOKEN"]
$site = $values["SITE_NAME"]
$port = $values["ERPNEXT_PORT"]

if ([string]::IsNullOrWhiteSpace($token)) {
  throw "ERPNEXT_API_TOKEN is empty or missing in $SourceEnv. Create an API key/secret for the ERPNext user in Desk > User > API Access, then put 'key:secret' in ERPNEXT_API_TOKEN."
}
if ([string]::IsNullOrWhiteSpace($port)) { $port = "8000" }
if ([string]::IsNullOrWhiteSpace($site)) { $site = "frontend" }

$dataDir = Join-Path $AppRoot "data"
if (-not (Test-Path $dataDir)) { New-Item -ItemType Directory -Path $dataDir | Out-Null }
$dbPath = (Join-Path $dataDir "copilot.sqlite").Replace("\", "/")

function New-Secret {
  $bytes = New-Object byte[] 32
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
  return [System.BitConverter]::ToString($bytes).Replace("-", "").ToLower()
}

$apiKey = New-Secret

$lines = @(
  "# Generated by setup-env.ps1 - do not commit this file.",
  "ERPNEXT_URL=http://localhost:$port",
  "ERPNEXT_SITE=$site",
  "ERPNEXT_AUTH_HEADER=token $token",
  "COPILOT_DB_PATH=$dbPath",
  "COPILOT_API_URL=http://127.0.0.1:4010",
  "COPILOT_API_PORT=4010",
  "COPILOT_API_KEY=$apiKey",
  "COPILOT_APP_URL=http://localhost:3010",
  "LOWDEFY_SECRET=$(New-Secret)",
  "LOWDEFY_SECRET_COPILOT_API_URL=http://127.0.0.1:4010",
  "LOWDEFY_SECRET_COPILOT_API_KEY=$apiKey",
  "LOWDEFY_SECRET_ERP_URL=http://localhost:$port",
  "LOWDEFY_SECRET_ERP_TOKEN=$token",
  "LOWDEFY_SECRET_SHOPIFY_STORE=$($values['SHOPIFY_STORE'])",
  "LOWDEFY_SECRET_SHOPIFY_TOKEN=$($values['SHOPIFY_ACCESS_TOKEN'])"
)

Set-Content -Path $TargetEnv -Value $lines -Encoding ascii -NoNewline:$false

Write-Host "Wrote $TargetEnv" -ForegroundColor Green
Write-Host "ERPNext: http://localhost:$port (site: $site)" -ForegroundColor Green
Write-Host "API token copied into ERPNEXT_AUTH_HEADER (value not printed)." -ForegroundColor Green
Write-Host "Next: .\start.ps1" -ForegroundColor Green
